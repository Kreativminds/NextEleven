// Run: node tests/regression_opponents_settings.js
// Source-level safeguards for Settings > Opponents Database. No database writes.
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const html=fs.readFileSync(require('node:path').join(__dirname,'..','index.html'),'utf8');
const start=html.indexOf('function opponentCatalogueDisplayKey(name) {');
const end=html.indexOf('async function renderOpponentsTab()',start);
assert(start>=0&&end>start,'Settings alias function present');
const context={};
vm.createContext(context);
vm.runInContext(html.slice(start,end),context);
const key=name=>vm.runInContext('opponentCatalogueDisplayKey('+JSON.stringify(name)+')',context);
assert.equal(key('Alta Lisboa'),key('Alta de Lisboa'));
assert.equal(key('Atlético'),key('Atlético CP'));
assert.equal(key('Fut. Benfica'),key('Futebol Benfica'),'Verified federation alias collapses to one club');
assert.equal(key('3FFF'),key('3F'),'Verified federation alias collapses to one club');
assert.equal(key('Olivais "A"'),key('Olivais "B"'),'Verified A/B squads share one SL Olivais club identity');
assert.notEqual(key('Olivais Sul'),key('SL Olivais'));
assert.notEqual(key('Benfica'),key('Benfica "B"'),'Squad B must not collapse into parent club');
for (const club of ['Belenenses','Cultural','Damaiense','Santa Maria','EF Belém','CF Estrela','Sacavenense']) {
  assert.equal(key(club+' "A"'),key(club),'Verified federation squad A should resolve to club');
  assert.equal(key(club+' "B"'),key(club),'Verified federation squad B should resolve to club');
}
assert.notEqual(key('Olivais Sul "A"'),key('SL Olivais'),'Olivais Sul squad must remain separate');
assert.notEqual(key('Benfica "B"'),key('Benfica'),'Unverified squad identity must remain distinct');
assert.equal(key('SL Olivais 2014'),key('SL Olivais'),'User-confirmed historical name belongs to SL Olivais');
assert.equal(key('Olivais "A"'),key('SL Olivais'),'Squad A belongs to SL Olivais');
assert.equal(key('Olivais "B"'),key('SL Olivais'),'Squad B belongs to SL Olivais');
assert.notEqual(key('Olivais Sul'),key('Olivais "A"'),'Olivais Sul must stay independent');
const render=html.slice(end,html.indexOf('// Set only by the',end));
assert(render.includes('const groups = new Map()'),'Groups aliases for display');
assert(render.includes('group.length > 1'),'Duplicate records individually accessible');
assert(render.includes('group.map(record =>'),'Every grouped opponent retains its own edit control');
assert(render.includes('editOpponent(${record.opponentId})'),'Each grouped record is independently editable');
assert(render.includes('const o = group[0]'),'Representative card is presentation only');
assert(render.includes("a.opponentName !== 'SL Olivais'"),'Canonical SL Olivais label preferred');
assert(!render.includes('o.ageGroup?'),'No age-group badge');
assert(!render.includes('o.level?'),'No division badge');
const save=html.slice(html.indexOf('async function saveOpponentFromForm()'),html.indexOf('async function deleteOpponent('));
assert(save.includes('const match = await findOpponentNameCollision(name);'),'Save checks duplicates');
assert(!save.includes('if (!_opponentDupOverride)'),'Duplicate bypass cannot disable checks');
assert(save.includes('existingOpponent?.ageGroup'),'Existing age-group metadata retained');
assert(save.includes('existingOpponent?.level'),'Existing division metadata retained');
assert(save.includes('existingOpponent.opponentName !== name'),'Rename detection is present');
assert(save.includes('game.opponent === existingOpponent.opponentName'),'Rename guard checks historical fixtures');
assert(save.indexOf('existingOpponent.opponentName !== name') < save.indexOf("DB.put('opponents', data)"),'Rename guard precedes database write');
const workflow=html.slice(html.indexOf('async function requestOpponentDeletion('),html.indexOf('// ── TRAINING SESSIONS',html.indexOf('async function requestOpponentDeletion(')));
assert(workflow.includes("Sync.supabaseRequest('POST', 'opponent_deletion_requests'"),'Users submit requests, not deletions');
assert(workflow.includes('request_reason: reason.trim()'),'Request includes user reason');
assert(workflow.includes("Sync.supabaseRequest('PATCH', 'opponent_deletion_requests'"),'Admin records review decision');
assert(workflow.includes('decision_reason: reason.trim()'),'Admin must explain decision');
assert(!workflow.includes("DB.softDelete('opponents'"),'Neither user nor reviewer directly deletes teams');
assert(!html.includes('async function deleteOpponent('),'Direct deletion action is removed');
assert(render.includes('requestOpponentDeletion('),'Settings offers deletion request');
assert(render.includes('reviewOpponentDeletionRequest('),'Settings includes admin review queue');
console.log('PASS: federation grouping, no direct delete, reviewed deletion requests and historical fixture protection');
